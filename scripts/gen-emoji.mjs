/**
 * The emoji list behind the reaction picker. Run with `node scripts/gen-emoji.mjs`.
 *
 * Built from Unicode's own emoji-test.txt rather than typed out, so the names
 * are the standard ones people actually search for ("red heart", not "heart"),
 * the grouping is the one every keyboard uses, and the set stays honest about
 * what exists. iOS draws these in Apple's own faces; the list is just which
 * characters to offer.
 *
 * Skin tone variants are dropped: they multiply the list by six and turn the
 * grid into a wall of the same hand. The base emoji is kept, and anyone who
 * wants a tone can still send one, because the server takes any single emoji.
 *
 * Writes lib/emoji.ts.
 */
import { writeFile, mkdir, readFile, access } from "node:fs/promises";
import path from "node:path";

const SRC = "https://unicode.org/Public/emoji/15.1/emoji-test.txt";
const CACHE = path.join(process.cwd(), "node_modules", ".cache", "manna-web");
const CACHED = path.join(CACHE, "emoji-test.txt");

async function source() {
  try {
    await access(CACHED);
  } catch {
    const res = await fetch(SRC);
    if (!res.ok) throw new Error(`emoji-test.txt: HTTP ${res.status}`);
    await mkdir(CACHE, { recursive: true });
    await writeFile(CACHED, await res.text());
  }
  return readFile(CACHED, "utf8");
}

/** The keyboard's own order, minus the two nobody reacts with. */
const GROUPS = [
  ["Smileys & Emotion", "Smileys"],
  ["People & Body", "People"],
  ["Animals & Nature", "Nature"],
  ["Food & Drink", "Food"],
  ["Travel & Places", "Travel"],
  ["Activities", "Activities"],
  ["Objects", "Objects"],
  ["Symbols", "Symbols"],
  ["Flags", "Flags"],
];

const text = await source();
let group = null;
const byGroup = new Map(GROUPS.map(([g]) => [g, []]));
const seen = new Set();

for (const line of text.split("\n")) {
  const g = line.match(/^# group: (.+)$/);
  if (g) { group = g[1].trim(); continue; }
  if (!group || !byGroup.has(group)) continue;
  const m = line.match(/^[0-9A-F ]+;\s*fully-qualified\s*#\s*(\S+)\s+E\d+\.\d+\s+(.+)$/);
  if (!m) continue;
  const [, emoji, name] = m;
  if (/skin tone/.test(name)) continue;
  if (seen.has(emoji)) continue;
  seen.add(emoji);
  byGroup.get(group).push([emoji, name.trim()]);
}

const groups = GROUPS.map(([g, label]) => ({ label, emoji: byGroup.get(g) }));
const total = groups.reduce((n, g) => n + g.emoji.length, 0);

const body = groups
  .map(
    (g) =>
      `  {\n    label: ${JSON.stringify(g.label)},\n    emoji: [\n` +
      g.emoji.map(([e, n]) => `      [${JSON.stringify(e)}, ${JSON.stringify(n)}],`).join("\n") +
      `\n    ],\n  },`,
  )
  .join("\n");

const out = `/**
 * Every emoji the reaction picker offers, in the order a keyboard shows them.
 *
 * GENERATED by scripts/gen-emoji.mjs from Unicode's emoji-test.txt. Do not
 * hand-edit. Skin tone variants are excluded on purpose; see the generator.
 *
 * ${total} emoji across ${groups.length} groups. Imported dynamically by the
 * picker so it never lands in the first load.
 */

/** One emoji and its standard name, which is also what search matches on. */
export type EmojiEntry = readonly [emoji: string, name: string];

export const EMOJI_GROUPS: readonly { label: string; emoji: readonly EmojiEntry[] }[] = [
${body}
];
`;

await writeFile(path.join(process.cwd(), "lib", "emoji.ts"), out);
console.log(`wrote lib/emoji.ts`);
console.log(`  ${total} emoji, ${groups.map((g) => `${g.label} ${g.emoji.length}`).join(", ")}`);
