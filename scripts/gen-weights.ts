/**
 * Regenerate lib/weights.ts from the frozen chapter signals. Run with
 * `npx tsx scripts/gen-weights.ts`. The output is committed; lib/weights.test.ts
 * asserts the committed table still matches what this produces.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { computeWeights, type ChapterSignals } from "../lib/weighting";
import { BOOKS } from "../lib/bible";

const signals = JSON.parse(
  readFileSync(new URL("../data/chapter-signals.json", import.meta.url), "utf8"),
) as ChapterSignals[];

const weighed = computeWeights(signals);
const byBook = new Map<string, number[]>();
for (const w of weighed) {
  if (!byBook.has(w.book)) byBook.set(w.book, []);
  byBook.get(w.book)!.push(w.minutes);
}

const lines: string[] = [];
for (const b of BOOKS) {
  const mins = byBook.get(b.name);
  if (!mins || mins.length !== b.chapters) {
    throw new Error(`${b.name}: expected ${b.chapters} chapters, got ${mins?.length ?? 0}`);
  }
  // Wrap at a readable width so a diff on this file stays reviewable.
  const wrapped: string[] = [];
  for (let i = 0; i < mins.length; i += 16) wrapped.push("    " + mins.slice(i, i + 16).join(", "));
  lines.push(`  ${JSON.stringify(b.name)}: [\n${wrapped.join(",\n")},\n  ],`);
}

const total = weighed.reduce((a, w) => a + w.minutes, 0);
const out = `/**
 * Study weight in minutes for each of the 1,189 chapters, indexed by chapter
 * number minus one.
 *
 * GENERATED by scripts/gen-weights.ts from data/chapter-signals.json via the
 * model in lib/weighting.ts. Do not hand-edit: lib/weights.test.ts checks that
 * this file is exactly what the model produces. To change a number, change the
 * model and regenerate.
 *
 * Total: ${total} minutes (${(total / 60).toFixed(1)} hours) across ${weighed.length} chapters.
 * Methodology: docs/weighting.md
 */

export const CHAPTER_WEIGHTS: Record<string, number[]> = {
${lines.join("\n")}
};

/** Total weighted study minutes for the whole Bible. */
export const TOTAL_WEIGHT_MINUTES = ${total};

/** Weight in minutes for a single chapter. */
export function weightOf(book: string, chapter: number): number {
  const list = CHAPTER_WEIGHTS[book];
  if (!list || chapter < 1 || chapter > list.length) {
    throw new Error(\`No weight for \${book} \${chapter}\`);
  }
  return list[chapter - 1];
}
`;

writeFileSync(new URL("../lib/weights.ts", import.meta.url), out);
console.log(`wrote lib/weights.ts — ${weighed.length} chapters, ${total} min (${(total / 60).toFixed(1)}h)`);

// Verse counts, from the same measured corpus. Used to keep the verse of the
// day inside the chapter it points at.
const versesByBook = new Map<string, number[]>();
for (const s of signals) {
  if (!versesByBook.has(s.b)) versesByBook.set(s.b, []);
  versesByBook.get(s.b)![s.c - 1] = s.v;
}
const vLines: string[] = [];
for (const b of BOOKS) {
  const vs = versesByBook.get(b.name)!;
  const wrapped: string[] = [];
  for (let i = 0; i < vs.length; i += 20) wrapped.push("    " + vs.slice(i, i + 20).join(", "));
  vLines.push(`  ${JSON.stringify(b.name)}: [\n${wrapped.join(",\n")},\n  ],`);
}
const totalVerses = signals.reduce((a, s) => a + s.v, 0);
writeFileSync(
  new URL("../lib/verses.ts", import.meta.url),
  `/**
 * Verse count for each chapter, indexed by chapter number minus one.
 *
 * GENERATED by scripts/gen-weights.ts. Used to keep the verse of the day inside
 * the chapter it names. Counted from the World English Bible; a handful of
 * chapters differ by one verse between translations where a line is joined or
 * split, so treat these as the length of a chapter rather than as gospel.
 *
 * ${totalVerses} verses across ${signals.length} chapters.
 */

export const VERSE_COUNTS: Record<string, number[]> = {
${vLines.join("\n")}
};

export function verseCount(book: string, chapter: number): number {
  const list = VERSE_COUNTS[book];
  if (!list || chapter < 1 || chapter > list.length) return 1;
  return list[chapter - 1];
}
`,
);
console.log(`wrote lib/verses.ts — ${totalVerses} verses`);
